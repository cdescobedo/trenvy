// Package render turns resolved values into bytes on disk.
package render

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/cdescobedo/envctl/internal/resolve"
)

// DotenvHeader is cosmetic: it tells a human where the file came from. It
// deliberately carries no hash — render bookkeeping lives in the state file,
// because a json target has nowhere to put a comment.
const DotenvHeader = "# Generated by envctl. Do not edit; run: envctl edit\n"

// Dotenv renders values as KEY="value" lines, sorted by name.
//
// Every value is double-quoted unconditionally rather than quoted only when
// needed. Connection strings — the most common value here — contain
// semicolons and equals signs, and conditional quoting is where dotenv writers
// usually get it wrong.
//
// The output is designed for dotenv-style readers such as docker compose's
// env_file: directive and DotNetEnv, which treat contents literally. It is NOT
// safe to source this file in a POSIX shell (e.g., with source .env or
// set -a; . .env) because $ is deliberately left unescaped and bash performs
// parameter expansion inside double quotes, potentially exposing secrets.
// Use envctl exec or envctl shell instead of sourcing rendered files.
func Dotenv(r resolve.Resolved) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(DotenvHeader)
	for _, name := range r.Names {
		if err := ValidateDotenvName(name); err != nil {
			return nil, err
		}
		fmt.Fprintf(&buf, "%s=%s\n", name, quote(r.Values[name]))
	}
	return buf.Bytes(), nil
}

// ValidateDotenvName rejects names that are not valid shell identifiers.
//
// Name validation belongs to the format, not the manifest: a json target's
// keys are free-form (auth0ClientID), while a dotenv key must be a valid
// shell identifier (letters, digits, underscore; no leading digit).
func ValidateDotenvName(name string) error {
	if name == "" {
		return fmt.Errorf("dotenv: empty variable name")
	}
	for i, c := range name {
		ok := c == '_' ||
			(c >= 'a' && c <= 'z') ||
			(c >= 'A' && c <= 'Z') ||
			(i > 0 && c >= '0' && c <= '9')
		if !ok {
			return fmt.Errorf("dotenv: %q is not a valid shell identifier; "+
				"use a json target, or rename the variable", name)
		}
	}
	return nil
}

func quote(v string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range v {
		switch c {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		default:
			b.WriteRune(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
