var update = flag.Bool("update", false, "rewrite golden files")

func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden %s: %v (run: go test ./internal/render/ -update)", path, err)
	}
	if string(got) != string(want) {
		t.Errorf("output differs from %s\n--- got ---\n%s\n--- want ---\n%s", path, got, want)
	}
}

func resolved(values map[string]string) resolve.Resolved {
	r := resolve.Resolved{Target: "t", Values: values}
	for k := range values {
		r.Names = append(r.Names, k)
	}
	// Values() sorts; mirror that here so tests exercise the real ordering.
	sort.Strings(r.Names)
	return r
}

func TestDotenvGolden(t *testing.T) {
	got, err := render.Dotenv(resolved(map[string]string{
		"APP_ENVIRONMENT":     "Development",
		"APP_URL":            "http://+:8080",
		"APP_DB_CONNECTION": "Server=localhost;Database=demo_project;Port=8675;User Id=postgres;Password=password;",
		"ALPHA_TOKEN":            "abc123",
	}))
	if err != nil {
		t.Fatalf("Dotenv: %v", err)
	}
	golden(t, "backend.env", got)
}

// Connection strings are full of the characters that break naive writers.
func TestDotenvQuotesAndEscapes(t *testing.T) {
	cases := map[string]struct{ in, want string }{
		"semicolons":    {"a;b;c", `X="a;b;c"`},
		"equals":        {"k=v", `X="k=v"`},
		"double quote":  {`say "hi"`, `X="say \"hi\""`},
		"backslash":     {`C:\path`, `X="C:\\path"`},
		"newline":       {"one\ntwo", `X="one\ntwo"`},
		"carriage ret":  {"one\rtwo", `X="one\rtwo"`},
		"empty":         {"", `X=""`},
		"leading space": {"  pad", `X="  pad"`},
		"dollar":        {"$NOT_EXPANDED", `X="$NOT_EXPANDED"`},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := render.Dotenv(resolved(map[string]string{"X": tc.in}))
			if err != nil {
				t.Fatalf("Dotenv: %v", err)
			}
			if !strings.Contains(string(got), tc.want) {
				t.Errorf("output does not contain %s\n%s", tc.want, got)
			}
		})
	}
}

func TestDotenvRejectsNamesThatAreNotShellIdentifiers(t *testing.T) {
	for _, bad := range []string{"auth0ClientID-x", "1LEADING", "has space", "has.dot", ""} {
		if err := render.ValidateDotenvName(bad); err == nil {
			t.Errorf("ValidateDotenvName(%q) = nil, want an error", bad)
		}
	}
	for _, good := range []string{"A", "_x", "auth0ClientID", "APP_URL", "A1_B2"} {
		if err := render.ValidateDotenvName(good); err != nil {
			t.Errorf("ValidateDotenvName(%q) = %v, want nil", good, err)
		}
	}
}

func TestDotenvFailsOnABadNameNamingIt(t *testing.T) {
	_, err := render.Dotenv(resolved(map[string]string{"has space": "v"}))
	if err == nil {
		t.Fatal("Dotenv accepted an invalid name")
	}
	if !strings.Contains(err.Error(), "has space") {
		t.Errorf("error does not name the variable: %v", err)
	}
}

// The header is cosmetic. It carries no hash, because render bookkeeping lives
// in the state file so that json targets can be tracked too.
func TestDotenvHeaderCarriesNoHash(t *testing.T) {
	got, err := render.Dotenv(resolved(map[string]string{"A": "1"}))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(got), "# Generated by envctl") {
		t.Errorf("missing header:\n%s", got)
	}
	if strings.Contains(string(got), "sum=") {
		t.Errorf("header carries a hash, which belongs in the state file:\n%s", got)
	}
}
